#!/usr/bin/env node
// Generates `src/shared/contracts/appServer.ts` from the pinned app-server
// JSON Schema bundle. The output is deterministic: definitions are emitted in
// the order they appear in definitions.json, then the envelope unions from the
// committed envelope files.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaRoot = resolve(root, 'vendor/bingo/app-server-schema/v1.0')
const definitionsPath = resolve(schemaRoot, 'definitions.json')
const outputPath = resolve(root, 'src/shared/contracts/appServer.ts')

const definitions = JSON.parse(await readFile(definitionsPath, 'utf8')).definitions
if (!definitions || typeof definitions !== 'object') {
  throw new Error('definitions.json has no definitions object')
}

function deref(ref, from) {
  if (typeof ref !== 'string') throw new Error(`Non-string ref in ${from}: ${JSON.stringify(ref)}`)
  const match = /#\/definitions\/(.+)$/.exec(ref)
  if (!match) throw new Error(`Unsupported ref in ${from}: ${ref}`)
  return match[1]
}

function renderType(schema, from = 'root', depth = 0) {
  if (depth > 24) return 'unknown'
  if (schema === undefined || schema === null) return 'unknown'
  if (typeof schema === 'boolean') return schema ? 'unknown' : 'never'
  if (schema.$ref) return deref(schema.$ref, from)
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  const type = schema.type
  if (type === 'null') return 'null'
  if (type === 'string') return 'string'
  if (type === 'boolean') return 'boolean'
  if (type === 'integer' || type === 'number') return 'number'
  if (type === 'array') return `Array<${renderType(schema.items ?? {}, from, depth + 1)}>`
  if (Array.isArray(type)) return type.map((entry) => renderType({ ...schema, type: entry }, from, depth + 1)).join(' | ')
  const branches = schema.oneOf ?? schema.anyOf
  if (Array.isArray(branches)) {
    return branches.map((branch) => renderType(branch, from, depth + 1)).join(' | ')
  }
  if (schema.allOf) return renderType({ ...schema, ...Object.assign({}, ...schema.allOf), allOf: undefined }, from, depth + 1)
  if (type === 'object' || schema.properties) {
    const props = schema.properties ?? {}
    const required = new Set(Array.isArray(schema.required) ? schema.required : [])
    const entries = Object.entries(props).map(([key, value]) => {
      const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
      return `${safeKey}${required.has(key) ? '' : '?'}: ${renderType(value, `${from}.${key}`, depth + 1)}`
    })
    if (entries.length === 0) return 'Record<string, unknown>'
    return `{ ${entries.join('; ')} }`
  }
  return 'unknown'
}

function renderDefinition(name, schema) {
  if (schema.type === 'object' && schema.properties) {
    const branches = schema.oneOf ?? schema.anyOf
    if (Array.isArray(branches) && branches.length > 0) {
      const common = renderType({ ...schema, oneOf: undefined, anyOf: undefined }, name)
      const variants = branches.map((branch, index) => renderType(branch, `${name}.variant${index}`)).join(' | ')
      return `export type ${name} = ${common} & (${variants})`
    }
    const props = schema.properties ?? {}
    const required = new Set(Array.isArray(schema.required) ? schema.required : [])
    const entries = Object.entries(props).map(([key, value]) => {
      const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
      return `  ${safeKey}${required.has(key) ? '' : '?'}: ${renderType(value, `${name}.${key}`)}`
    })
    return `export interface ${name} {\n${entries.join('\n')}\n}`
  }
  return `export type ${name} = ${renderType(schema, name)}`
}

const lines = [
  '// @generated by scripts/generate-app-server-types.mjs — do not edit by hand.',
  '// Source: vendor/bingo/app-server-schema/v1.0 (bingo app-server v1.0, schema bundle v1).',
  '// Unknown JSON fields are additive within protocol major 1; generated fields are',
  '// intentionally the committed contract, not an exhaustive wire validator.',
  ''
]

for (const name of Object.keys(definitions)) {
  lines.push(`// ${name}`)
  lines.push(renderDefinition(name, definitions[name]))
  lines.push('')
}

function envelopeBranches(file) {
  const schema = JSON.parse(readFileSync(resolve(schemaRoot, 'envelopes', file), 'utf8'))
  const branches = schema.oneOf ?? schema.anyOf
  if (!Array.isArray(branches)) return `  | ${renderType(schema, file)}`
  const topProps = schema.properties ?? {}
  const topRequired = new Set(Array.isArray(schema.required) ? schema.required : [])
  return branches.map((branch, index) => {
    const props = { ...topProps, ...(branch.properties ?? {}) }
    const required = new Set([...topRequired, ...(Array.isArray(branch.required) ? branch.required : [])])
    const entries = Object.entries(props).map(([key, value]) => {
      const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
      return `${safeKey}${required.has(key) ? '' : '?'}: ${renderType(value, `${file}[${index}].${key}`)}`
    })
    return `  | { ${entries.join('; ')} }`
  }).join('\n')
}

lines.push('export type AppServerRequest =\n' + envelopeBranches('envelope.request.json'))
lines.push('')
lines.push('export type AppServerNotification =\n' + envelopeBranches('envelope.notification.json'))
lines.push('')
lines.push('export type AppServerClientNotification =\n' + envelopeBranches('envelope.clientNotification.json'))
lines.push('')

const responseSchema = JSON.parse(readFileSync(resolve(schemaRoot, 'envelopes', 'envelope.response.json'), 'utf8'))
const errorSchema = JSON.parse(readFileSync(resolve(schemaRoot, 'envelopes', 'envelope.error.json'), 'utf8'))
lines.push(`export type AppServerResponse = ${renderType(responseSchema, 'envelope.response')}`)
lines.push('')
lines.push(`export type AppServerRpcError = ${renderType(errorSchema, 'envelope.error')}`)
lines.push('')

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, lines.join('\n') + '\n')
console.log(`wrote ${outputPath} (${lines.length} lines)`)
